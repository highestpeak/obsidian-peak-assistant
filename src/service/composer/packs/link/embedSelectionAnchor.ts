/**
 * Source-backed Obsidian block anchors for persisted embed selections.
 *
 * Obsidian can transclude a paragraph, list, quote, callout, or heading through
 * `![[note#^block-id]]`; it cannot address an arbitrary character range. The
 * preview resolves a selected DOM range upward to one semantic container before
 * this planner maps that complete block back to lossless Markdown source.
 */

import { parseComposerDocument } from '../../documentParser';

const ANCHORABLE_KINDS = new Set(['paragraph', 'heading', 'list', 'task', 'quote', 'callout']);
const EXISTING_ANCHOR_RE = /\s\^([A-Za-z0-9-]+)\s*$/;

export type EmbedSelectionAnchorPlan =
	| { ok: true; anchor: string; nextText: string; reused: boolean }
	| { ok: false; reason: 'selection-not-a-single-block' | 'selection-ambiguous' };

export type EmbedSelectionRangePlan =
	| { ok: true; startAnchor: string; endAnchor: string; nextText: string; reused: boolean }
	| { ok: false; reason: 'selection-not-a-contiguous-block-range' | 'selection-ambiguous' };

export type ManagedEmbedSelectionAnchors =
	| { kind: 'block'; anchor: string }
	| { kind: 'range'; startAnchor: string; endAnchor: string };

/**
 * Add (or reuse) a compatible Obsidian block anchor for a selected rendered
 * Markdown semantic block. `anchorId` is generated by the app layer so tests
 * stay deterministic and this pure planner never touches platform randomness.
 */
export function planEmbedSelectionAnchor(
	sourceText: string,
	selectedBlockText: string,
	anchorId: string,
	previousSelection?: ManagedEmbedSelectionAnchors,
): EmbedSelectionAnchorPlan {
	const expected = normalizeVisibleText(selectedBlockText);
	if (!expected) return { ok: false, reason: 'selection-not-a-single-block' };

	const preparedSource = previousSelection
		? removeManagedEmbedSelectionAnchors(sourceText, previousSelection)
		: sourceText;
	const snapshot = parseComposerDocument(preparedSource);
	const matches = snapshot.blocks.flatMap((block) => {
		const candidates: AnchorCandidate[] = ANCHORABLE_KINDS.has(block.kind)
			? [{ to: block.source.to, raw: block.renderModel.raw, unit: false }]
			: [];
		for (const unit of block.units) {
			const raw = preparedSource.slice(unit.from, unit.to);
			if (raw.trim()) candidates.push({ to: unit.to, raw, unit: true });
		}
		return candidates.filter((candidate) => normalizeVisibleText(candidate.raw) === expected);
	});
	if (matches.length === 0) return { ok: false, reason: 'selection-not-a-single-block' };
	const unitMatches = matches.filter((match) => match.unit);
	const preferred = unitMatches.length > 0 ? unitMatches : matches;
	if (preferred.length > 1) return { ok: false, reason: 'selection-ambiguous' };

	const block = preferred[0];
	const raw = block.raw;
	const existing = EXISTING_ANCHOR_RE.exec(raw);
	if (existing) return { ok: true, anchor: existing[1], nextText: preparedSource, reused: true };

	const anchor = uniqueAnchorId(preparedSource, anchorId);
	const nextText = `${preparedSource.slice(0, block.to)} ^${anchor}${preparedSource.slice(block.to)}`;
	return { ok: true, anchor, nextText, reused: false };
}

/**
 * Persist several consecutive Markdown blocks as one Composer range. The
 * target note receives boundary anchors, while the parent note keeps one
 * logical embed with range metadata. This intentionally preserves the source
 * bytes between the boundaries, including blank lines and inline formatting.
 */
export function planEmbedSelectionRange(
	sourceText: string,
	selectedBlockTexts: readonly string[],
	anchorId: string,
	previousSelection?: ManagedEmbedSelectionAnchors,
): EmbedSelectionRangePlan {
	const expected = selectedBlockTexts.map(normalizeVisibleText).filter(Boolean);
	if (expected.length < 2 || expected.length !== selectedBlockTexts.length) {
		return { ok: false, reason: 'selection-not-a-contiguous-block-range' };
	}
	const preparedSource = previousSelection
		? removeManagedEmbedSelectionAnchors(sourceText, previousSelection)
		: sourceText;
	const snapshot = parseComposerDocument(preparedSource);
	const matches: Array<{ first: number; last: number }> = [];
	for (let first = 0; first <= snapshot.blocks.length - expected.length; first += 1) {
		const candidate = snapshot.blocks.slice(first, first + expected.length);
		if (
			candidate.length === expected.length
			&& candidate.every((block, index) => ANCHORABLE_KINDS.has(block.kind) && normalizeVisibleText(block.renderModel.raw) === expected[index])
		) matches.push({ first, last: first + expected.length - 1 });
	}
	if (matches.length === 0) return { ok: false, reason: 'selection-not-a-contiguous-block-range' };
	if (matches.length > 1) return { ok: false, reason: 'selection-ambiguous' };

	const { first, last } = matches[0];
	const startBlock = snapshot.blocks[first];
	const endBlock = snapshot.blocks[last];
	const existingStart = anchorFromRaw(startBlock.renderModel.raw);
	const existingEnd = anchorFromRaw(endBlock.renderModel.raw);
	const startAnchor = existingStart ?? uniqueAnchorId(sourceText, `${anchorId}-start`);
	const sourceWithStart = existingStart
		? preparedSource
		: insertAnchor(preparedSource, startBlock.source.to, startAnchor);
	const endOffset = endBlock.source.to + (existingStart ? 0 : ` ^${startAnchor}`.length);
	const endAnchor = existingEnd ?? uniqueAnchorId(sourceWithStart, `${anchorId}-end`);
	const nextText = existingEnd
		? sourceWithStart
		: insertAnchor(sourceWithStart, endOffset, endAnchor);
	return {
		ok: true,
		startAnchor,
		endAnchor,
		nextText,
		reused: Boolean(existingStart && existingEnd),
	};
}

/**
 * Remove only exact anchors previously recorded in Composer metadata and owned
 * by Composer's reserved `peak-` namespace. Other Obsidian block IDs survive.
 */
export function removeManagedEmbedSelectionAnchors(
	sourceText: string,
	selection: ManagedEmbedSelectionAnchors,
): string {
	const anchors = selection.kind === 'block'
		? [selection.anchor]
		: [selection.startAnchor, selection.endAnchor];
	return [...new Set(anchors)].reduce((current, anchor) => {
		if (!anchor.startsWith('peak-')) return current;
		const escaped = anchor.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
		const boundary = new RegExp(`[ \\t]+\\^${escaped}(?=[ \\t]*(?:\\r?\\n|$))`, 'g');
		return current.replace(boundary, '');
	}, sourceText);
}

/** Read the exact source slice bounded by two persisted Composer range anchors. */
export function extractEmbedSelectionRange(
	sourceText: string,
	startAnchor: string,
	endAnchor: string,
): { resolved: boolean; text: string } {
	const snapshot = parseComposerDocument(sourceText);
	const start = snapshot.blocks.findIndex((block) => anchorFromRaw(block.renderModel.raw) === startAnchor);
	const end = snapshot.blocks.findIndex((block) => anchorFromRaw(block.renderModel.raw) === endAnchor);
	if (start === -1 || end === -1 || start > end) return { resolved: false, text: '' };
	return {
		resolved: true,
		text: sourceText.slice(snapshot.blocks[start].source.from, snapshot.blocks[end].source.to),
	};
}

interface AnchorCandidate {
	to: number;
	raw: string;
	unit: boolean;
}

/** Normalize the rendered-text equivalents needed to match an Obsidian DOM block. */
export function normalizeVisibleText(markdown: string): string {
	return markdown
		.replace(/^\s{0,3}>\s?/gm, '')
		.replace(/^\s*(?:[-*+] |\d+[.)] )/gm, '')
		.replace(/^\s{0,3}#{1,6}\s+/gm, '')
		.replace(/\[\[([^\]|#]+)(?:#[^\]|]+)?\|([^\]]+)\]\]/g, '$2')
		.replace(/\[\[([^\]|#]+)(?:#[^\]|]+)?\]\]/g, '$1')
		.replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')
		.replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
		.replace(/<[^>]+>/g, '')
		.replace(/(\*\*|__|~~|==|\*|_|`)/g, '')
		.replace(/\s\^[A-Za-z0-9-]+\s*$/g, '')
		.replace(/\\([\\`*{}\[\]()#+\-.!_>])/g, '$1')
		.replace(/\s+/g, ' ')
		.trim();
}

function uniqueAnchorId(sourceText: string, requested: string): string {
	let candidate = requested;
	let suffix = 2;
	while (sourceText.includes(`^${candidate}`)) {
		candidate = `${requested}-${suffix}`;
		suffix += 1;
	}
	return candidate;
}

function anchorFromRaw(raw: string): string | undefined {
	return EXISTING_ANCHOR_RE.exec(raw)?.[1];
}

function insertAnchor(sourceText: string, offset: number, anchor: string): string {
	return `${sourceText.slice(0, offset)} ^${anchor}${sourceText.slice(offset)}`;
}
