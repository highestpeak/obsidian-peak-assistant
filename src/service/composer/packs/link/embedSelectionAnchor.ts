/**
 * Source-backed Obsidian block anchors for persisted embed selections.
 *
 * Obsidian can transclude a paragraph, list, quote, callout, or heading through
 * `![[note#^block-id]]`; it cannot address an arbitrary character range. This
 * planner therefore fails closed unless the rendered selection is exactly one
 * Markdown semantic block. The app layer owns the vault write; this module only
 * identifies the block and returns a lossless source splice.
 */

import { parseComposerDocument } from '../../documentParser';

const ANCHORABLE_KINDS = new Set(['paragraph', 'heading', 'list', 'task', 'quote', 'callout']);
const EXISTING_ANCHOR_RE = /\s\^([A-Za-z0-9-]+)\s*$/;

export type EmbedSelectionAnchorPlan =
	| { ok: true; anchor: string; nextText: string; reused: boolean }
	| { ok: false; reason: 'selection-not-a-single-block' | 'selection-ambiguous' };

/**
 * Add (or reuse) a compatible Obsidian block anchor for a fully selected
 * rendered Markdown block. `anchorId` is generated by the app layer so tests
 * stay deterministic and this pure planner never touches platform randomness.
 */
export function planEmbedSelectionAnchor(
	sourceText: string,
	selectedBlockText: string,
	anchorId: string,
): EmbedSelectionAnchorPlan {
	const expected = normalizeVisibleText(selectedBlockText);
	if (!expected) return { ok: false, reason: 'selection-not-a-single-block' };

	const snapshot = parseComposerDocument(sourceText);
	const matches = snapshot.blocks.flatMap((block) => {
		const candidates: AnchorCandidate[] = ANCHORABLE_KINDS.has(block.kind)
			? [{ to: block.source.to, raw: block.renderModel.raw, unit: false }]
			: [];
		for (const unit of block.units) {
			const raw = sourceText.slice(unit.from, unit.to);
			if (raw.trim()) candidates.push({ to: unit.to, raw, unit: true });
		}
		return candidates.filter((candidate) => normalizeVisibleText(candidate.raw) === expected);
	});
	if (matches.length === 0) return { ok: false, reason: 'selection-not-a-single-block' };
	const unitMatches = matches.filter((match) => match.unit);
	const preferred = unitMatches.length > 0 ? unitMatches : matches;
	if (preferred.length > 1) return { ok: false, reason: 'selection-ambiguous' };

	const block = preferred[0];
	const raw = block.raw;
	const existing = EXISTING_ANCHOR_RE.exec(raw);
	if (existing) return { ok: true, anchor: existing[1], nextText: sourceText, reused: true };

	const anchor = uniqueAnchorId(sourceText, anchorId);
	const nextText = `${sourceText.slice(0, block.to)} ^${anchor}${sourceText.slice(block.to)}`;
	return { ok: true, anchor, nextText, reused: false };
}

interface AnchorCandidate {
	to: number;
	raw: string;
	unit: boolean;
}

/** Normalize the rendered-text equivalents needed to match an Obsidian DOM block. */
export function normalizeVisibleText(markdown: string): string {
	return markdown
		.replace(/^\s{0,3}>\s?/gm, '')
		.replace(/^\s*(?:[-*+] |\d+[.)] )/gm, '')
		.replace(/^\s{0,3}#{1,6}\s+/gm, '')
		.replace(/\[\[([^\]|#]+)(?:#[^\]|]+)?\|([^\]]+)\]\]/g, '$2')
		.replace(/\[\[([^\]|#]+)(?:#[^\]|]+)?\]\]/g, '$1')
		.replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')
		.replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
		.replace(/<[^>]+>/g, '')
		.replace(/(\*\*|__|~~|==|\*|_|`)/g, '')
		.replace(/\s\^[A-Za-z0-9-]+\s*$/g, '')
		.replace(/\\([\\`*{}\[\]()#+\-.!_>])/g, '$1')
		.replace(/\s+/g, ' ')
		.trim();
}

function uniqueAnchorId(sourceText: string, requested: string): string {
	let candidate = requested;
	let suffix = 2;
	while (sourceText.includes(`^${candidate}`)) {
		candidate = `${requested}-${suffix}`;
		suffix += 1;
	}
	return candidate;
}
