/**
 * Memory primitives for the self-hosted agent harness. See spec §3.8.
 *
 * Working memory is implemented via `MemoryBlock` — named, prioritized chunks
 * with an independent token budget. Compaction (handled by ContextManager)
 * uses `priority` + `evictable` to decide which blocks to keep when the tier
 * context window is tight.
 *
 * Procedural memory is stored as `Reflection` rows in chat.sqlite. M3 ships
 * the store only; producing reflections is an offline batch job slated for
 * M5+ (see spec §3.8 "离线批处理产物").
 *
 * Episodic + semantic memory continue to live in chat.sqlite / vault.sqlite
 * via existing repos — we do not re-implement them here.
 */

/**
 * Named, budgeted slot in the working-memory bag passed to ContextManager.
 *
 * `name` follows the spec's enumerated convention but is open-typed (string)
 * so callers can introduce ad-hoc blocks for new agents without churning a
 * shared union.
 */
export interface MemoryBlock {
    /** Stable identifier within a MemoryStore — also used as JSON key in serialization. */
    id: string;
    /** Display / system-prompt label, e.g. "task", "vault_ctx". */
    name: string;
    /** Block payload, rendered as text into the system prompt or message stream. */
    content: string;
    /**
     * Compaction priority. Higher = retained longer. ContextManager evicts
     * blocks in ascending priority order until under budget.
     */
    priority: number;
    /**
     * Soft per-block ceiling in tokens. When exceeded the block content is
     * head-truncated by ContextManager.estimateTokens before rendering. A
     * value of 0 or undefined means "no per-block cap".
     */
    tokenBudget?: number;
    /**
     * If false, the block is pinned: ContextManager never drops it even when
     * over budget. Use sparingly — typical "system" / "task" blocks are
     * evictable=false.
     */
    evictable: boolean;
}

/** Read-only in-memory view of registered blocks. */
export interface MemoryStoreSnapshot {
    blocks: ReadonlyArray<MemoryBlock>;
}

/**
 * Distilled insight produced by an offline reflection batch job.
 * Source rows live in the `harness_reflection` table (chat.sqlite).
 */
export interface Reflection {
    /** Auto-increment id; undefined until inserted. */
    id?: number;
    /** Loop run that produced the insight (links to trace storage). */
    loopId: string;
    /** Owning agent name — used to scope retrieval to a single agent. */
    agentName: string;
    /** Free-form natural-language insight, generated by an LLM in M5+. */
    insight: string;
    /** Unix ms. */
    createdAt: number;
    /** Optional JSON-serializable bag of structured fields (e.g. tags, scores). */
    metadata?: Record<string, unknown>;
}

/**
 * Minimal contract a backing store must satisfy for the harness to persist
 * reflections. Kept narrow so it can be implemented over SQLite, in-memory
 * arrays (tests), or remote stores.
 */
export interface ReflectionStoreLike {
    insert(reflection: Reflection): Promise<Reflection>;
    listByAgent(agentName: string, limit?: number): Promise<Reflection[]>;
    listByLoop(loopId: string): Promise<Reflection[]>;
}
